import com.charahua.gestocitassanna.presentation.components.MinimalCard
import com.charahua.gestocitassanna.presentation.components.MinimalTextField
import com.charahua.gestocitassanna.presentation.components.MinimalTopBar
import com.charahua.gestocitassanna.presentation.viewmodel.CitasViewModel
import com.charahua.gestocitassanna.ui.theme.*
import java.text.SimpleDateFormat
import java.util.*

@Composable
fun ReservarCitaScreen(
    viewModel: CitasViewModel,
    pacienteId: Long,
    onBookingSuccess: () -> Unit,
    onBack: () -> Unit
) {
    val context = LocalContext.current
    var step by remember { mutableIntStateOf(1) }

    val sedes by viewModel.sedes.collectAsState()
    val especialidades by viewModel.especialidades.collectAsState()
    val medicos by viewModel.medicos.collectAsState()
    val aseguradoras by viewModel.aseguradoras.collectAsState()
    val tarifaBase by viewModel.tarifaActual.collectAsState()

    var selectedSedeId by remember { mutableStateOf<Long?>(null) }
    var selectedSedeNombre by remember { mutableStateOf("") }

    var selectedEspId by remember { mutableStateOf<Long?>(null) }
    var selectedEspNombre by remember { mutableStateOf("") }

    var selectedMedicoId by remember { mutableStateOf<Long?>(null) }
    var selectedMedicoNombre by remember { mutableStateOf("") }

    val todayFormatted = remember {
        val cal = Calendar.getInstance()
        val year = cal.get(Calendar.YEAR)
        val month = cal.get(Calendar.MONTH) + 1
        val day = cal.get(Calendar.DAY_OF_MONTH)
        String.format(Locale.getDefault(), "%04d-%02d-%02d", year, month, day)
    }

    var fecha by remember { mutableStateOf(todayFormatted) }
    var hora by remember { mutableStateOf("09:00 AM") }
    var modalidad by remember { mutableStateOf("Presencial en Sede") }
    var selectedAseguradoraId by remember { mutableStateOf<Long?>(null) }
    var selectedAseguradoraNombre by remember { mutableStateOf("Particular / Sin Seguro") }
    var motivo by remember { mutableStateOf("") }

    var metodoPago by remember { mutableStateOf("Tarjeta de Crédito / Débito") }
    var numeroTarjeta by remember { mutableStateOf("") }
    var nombreTitular by remember { mutableStateOf("") }
    var fechaExpira by remember { mutableStateOf("") }
    var cvv by remember { mutableStateOf("") }
    var celularYape by remember { mutableStateOf("") }
    var codigoYape by remember { mutableStateOf("") }
    var pagoErrorMsg by remember { mutableStateOf<String?>(null) }

    var isProcessingPayment by remember { mutableStateOf(false) }
    var isPaymentSuccessAnimated by remember { mutableStateOf(false) }

    var numOperacionGenerated by remember { mutableStateOf("") }
    var numBoletaGenerated by remember { mutableStateOf("") }
    var montoFinalCalculado by remember { mutableDoubleStateOf(0.0) }

    val bookingResult by viewModel.bookingResult.collectAsState()

    val dynamicFechas = remember {
        val list = mutableListOf<Pair<String, String>>()
        val cal = Calendar.getInstance()
        val esLocale = Locale.Builder().setLanguage("es").setRegion("PE").build()
        val sdfFull = SimpleDateFormat("EEEE d 'de' MMMM", esLocale)

        for (i in 0..6) {
            val yr = cal.get(Calendar.YEAR)
            val mo = cal.get(Calendar.MONTH) + 1
            val dy = cal.get(Calendar.DAY_OF_MONTH)
            val valStr = String.format(Locale.getDefault(), "%04d-%02d-%02d", yr, mo, dy)

            val fullText = sdfFull.format(cal.time).replaceFirstChar { it.uppercase() }
            val labelStr = when (i) {
                0 -> "Hoy ($valStr)"
                1 -> "Mañana ($valStr)"
                else -> "$fullText ($valStr)"
            }
            list.add(Pair(valStr, labelStr))
            cal.add(Calendar.DAY_OF_YEAR, 1)
        }
        list
    }

    val showCalendarPicker = {
        val nowCal = Calendar.getInstance()
        DatePickerDialog(
            context,
            { _, year, month, dayOfMonth ->
                val chosenFecha = String.format(Locale.getDefault(), "%04d-%02d-%02d", year, month + 1, dayOfMonth)
                fecha = chosenFecha
            },
            nowCal.get(Calendar.YEAR),
            nowCal.get(Calendar.MONTH),
            nowCal.get(Calendar.DAY_OF_MONTH)
        ).apply {
            datePicker.minDate = System.currentTimeMillis() - 1000
            show()
        }
    }

    montoFinalCalculado = if (selectedAseguradoraId != null) {
        val coberturaPorcentaje = when (selectedAseguradoraNombre) {
            "Rímac Seguros" -> 80
            "Pacífico Seguros" -> 85
            "La Positiva Sanitas" -> 90
            else -> 75
        }
        tarifaBase * (1.0 - (coberturaPorcentaje / 100.0))
    } else {
        tarifaBase
    }

    LaunchedEffect(Unit) {
        viewModel.resetBookingResult()
        viewModel.loadBookingData()
    }

    LaunchedEffect(bookingResult) {
        if (bookingResult != null && bookingResult!!.isSuccess) {
            isProcessingPayment = false
            isPaymentSuccessAnimated = true
            step = 8
        } else if (bookingResult != null && bookingResult!!.isFailure) {
            isProcessingPayment = false
            pagoErrorMsg = bookingResult!!.exceptionOrNull()?.localizedMessage ?: "Error procesando la transacción"
        }
    }

    val backAction: (() -> Unit)? = when {
        isProcessingPayment -> null
        step in 2..7 -> { { step-- } }
        step == 1 -> onBack
        else -> null
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .background(SannaBackground)
    ) {
        MinimalTopBar(
            title = if (step == 8) "Comprobante de Reserva" else "Reservar Cita Médica",
            onBackClick = backAction
        )

        if (step < 8) {
            Column(modifier = Modifier.padding(horizontal = 20.dp, vertical = 6.dp)) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Text(
                        text = "PASO $step DE 7",
                        fontSize = 11.sp,
                        fontWeight = FontWeight.Bold,
                        color = SannaSecondaryText
                    )
                    Text(
                        text = when (step) {
                            1 -> "Sede"
                            2 -> "Especialidad"
                            3 -> "Médico"
                            4 -> "Fecha"
                            5 -> "Horario"
                            6 -> "Modalidad y Cobertura"
                            else -> "Pasarela de Pago"
                        },
                        fontSize = 12.sp,
                        fontWeight = FontWeight.SemiBold,
                        color = SannaPrimary
                    )
                }
                Spacer(modifier = Modifier.height(6.dp))
                LinearProgressIndicator(
                    progress = { step / 7f },
                    modifier = Modifier.fillMaxWidth().height(4.dp),
                    color = SannaPrimary,
                    trackColor = SannaSecondary
                )
            }
        }

        Spacer(modifier = Modifier.height(8.dp))

        AnimatedContent(
            targetState = step,
            transitionSpec = {
                slideInHorizontally(initialOffsetX = { 300 }) + fadeIn() togetherWith
                        slideOutHorizontally(targetOffsetX = { -300 }) + fadeOut()
            },
            label = "StepTransition",
            modifier = Modifier.weight(1f)
        ) { currentStep ->
            Box(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(horizontal = 20.dp)
            ) {
                when (currentStep) {
                    1 -> {
                        Column(modifier = Modifier.fillMaxSize()) {
                            Text("Selecciona la Sede SANNA", fontWeight = FontWeight.Bold, fontSize = 20.sp, color = SannaPrimary)
                            Text("Escoge la clínica de tu preferencia para la atención", fontSize = 13.sp, color = SannaSecondaryText)
                            Spacer(modifier = Modifier.height(16.dp))

                            LazyColumn(verticalArrangement = Arrangement.spacedBy(10.dp), modifier = Modifier.weight(1f)) {
                                items(sedes) { sede ->
                                    val isSelected = selectedSedeId == sede.id
                                    Card(
                                        shape = RoundedCornerShape(14.dp),
                                        colors = CardDefaults.cardColors(containerColor = if (isSelected) SannaSecondary else SannaSurface),
                                        border = BorderStroke(if (isSelected) 2.dp else 1.dp, if (isSelected) SannaPrimary else SannaBorder),
                                        modifier = Modifier
                                            .fillMaxWidth()
                                            .clickable {
                                                selectedSedeId = sede.id
                                                selectedSedeNombre = sede.nombre
                                                step = 2
                                            }
                                    ) {
                                        Column(modifier = Modifier.padding(16.dp)) {
                                            Text(sede.nombre, fontWeight = FontWeight.Bold, fontSize = 16.sp, color = SannaPrimary)
                                            Spacer(modifier = Modifier.height(4.dp))
                                            Text("📍 ${sede.direccion} - ${sede.distrito}", fontSize = 13.sp, color = SannaSecondaryText)
                                            Text("📞 Central: ${sede.telefono}", fontSize = 12.sp, color = SannaSecondaryText)
                                        }
                                    }
                                }
                            }
                        }
                    }
                    2 -> {
                        Column(modifier = Modifier.fillMaxSize()) {
                            Text("Selecciona Especialidad Médica", fontWeight = FontWeight.Bold, fontSize = 20.sp, color = SannaPrimary)
                            Text("Sede seleccionada: $selectedSedeNombre", fontSize = 13.sp, color = SannaSecondaryText)
                            Spacer(modifier = Modifier.height(16.dp))

                            LazyColumn(verticalArrangement = Arrangement.spacedBy(10.dp), modifier = Modifier.weight(1f)) {
                                items(especialidades) { esp ->
                                    Card(
                                        shape = RoundedCornerShape(14.dp),
                                        colors = CardDefaults.cardColors(containerColor = SannaSurface),
                                        border = BorderStroke(1.dp, SannaBorder),
                                        modifier = Modifier
                                            .fillMaxWidth()
                                            .clickable {
                                                selectedEspId = esp.id
                                                selectedEspNombre = esp.nombre
                                                selectedSedeId?.let { sId ->
                                                    viewModel.loadMedicosFor(sId, esp.id)
                                                }
                                                step = 3
                                            }
                                    ) {
                                        Column(modifier = Modifier.padding(16.dp)) {
                                            Text(esp.nombre, fontWeight = FontWeight.Bold, fontSize = 16.sp, color = SannaPrimary)
                                            Spacer(modifier = Modifier.height(4.dp))
                                            Text(esp.descripcion, fontSize = 13.sp, color = SannaSecondaryText)
                                        }
                                    }
                                }
                            }
                        }
                    }
                    3 -> {
                        Column(modifier = Modifier.fillMaxSize()) {
                            Text("Selecciona Médico Especialista", fontWeight = FontWeight.Bold, fontSize = 20.sp, color = SannaPrimary)
                            Text("Especialidad: $selectedEspNombre en $selectedSedeNombre", fontSize = 13.sp, color = SannaSecondaryText)
                            Spacer(modifier = Modifier.height(16.dp))

                            if (medicos.isEmpty()) {
                                Box(modifier = Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
                                    Text("No se encontraron médicos asignados a esta especialidad en la sede seleccionada.", color = SannaError, fontSize = 14.sp)
                                }
                            } else {
                                LazyColumn(verticalArrangement = Arrangement.spacedBy(10.dp), modifier = Modifier.weight(1f)) {
                                    items(medicos) { med ->
                                        Card(
                                            shape = RoundedCornerShape(14.dp),
                                            colors = CardDefaults.cardColors(containerColor = SannaSurface),
                                            border = BorderStroke(1.dp, SannaBorder),
                                            modifier = Modifier
                                                .fillMaxWidth()
                                                .clickable {
                                                    selectedMedicoId = med.id
                                                    selectedMedicoNombre = "Dr. ${med.nombre} ${med.apellido}"
                                                    step = 4
                                                }
                                        ) {
                                            Row(
                                                modifier = Modifier.padding(16.dp),
                                                verticalAlignment = Alignment.CenterVertically
                                            ) {
                                                Column(modifier = Modifier.weight(1f)) {
                                                    Text("Dr. ${med.nombre} ${med.apellido}", fontWeight = FontWeight.Bold, fontSize = 16.sp, color = SannaPrimary)
                                                    Spacer(modifier = Modifier.height(4.dp))
                                                    Text("Colegiatura: ${med.colegiatura}", fontSize = 13.sp, color = SannaSecondaryText)
                                                }
                                                Surface(
                                                    color = SannaSecondary,
                                                    shape = RoundedCornerShape(8.dp)
                                                ) {
                                                    Text("Seleccionar", fontSize = 12.sp, fontWeight = FontWeight.Bold, color = SannaPrimary, modifier = Modifier.padding(horizontal = 10.dp, vertical = 6.dp))
                                                }
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                    4 -> {
                        Column(
                            modifier = Modifier
                                .fillMaxSize()
                                .verticalScroll(rememberScrollState())
                        ) {
                            Text("Selecciona Fecha de Atención", fontWeight = FontWeight.Bold, fontSize = 20.sp, color = SannaPrimary)
                            Text("Médico: $selectedMedicoNombre", fontSize = 13.sp, color = SannaSecondaryText)
                            Spacer(modifier = Modifier.height(16.dp))

                            Text("Fechas inmediatas disponibles:", fontSize = 14.sp, fontWeight = FontWeight.SemiBold, color = SannaPrimary)
                            Spacer(modifier = Modifier.height(8.dp))

                            dynamicFechas.forEach { item ->
                                val fVal = item.first
                                val fLabel = item.second
                                val isSel = fecha == fVal
                                Card(
                                    shape = RoundedCornerShape(12.dp),
                                    colors = CardDefaults.cardColors(containerColor = if (isSel) SannaSecondary else SannaSurface),
                                    border = BorderStroke(if (isSel) 2.dp else 1.dp, if (isSel) SannaPrimary else SannaBorder),
                                    modifier = Modifier
                                        .fillMaxWidth()
                                        .padding(vertical = 4.dp)
                                        .clickable { fecha = fVal }
                                ) {
                                    Box(modifier = Modifier.padding(14.dp)) {
                                        Text("📅 $fLabel", fontWeight = FontWeight.Bold, fontSize = 14.sp, color = SannaPrimary)
                                    }
                                }
                            }

                            Spacer(modifier = Modifier.height(12.dp))
                            MinimalButton(
                                text = "📅 Abrir Calendario de Fechas Futuras",
                                onClick = { showCalendarPicker() },
                                modifier = Modifier.fillMaxWidth(),
                                isPrimary = false
                            )

                            Spacer(modifier = Modifier.height(12.dp))
                            Text("Fecha elegida: $fecha", fontSize = 14.sp, fontWeight = FontWeight.Bold, color = SannaPrimary)

                            Spacer(modifier = Modifier.height(20.dp))
                            MinimalButton(text = "Continuar a Horarios", onClick = { step = 5 }, modifier = Modifier.fillMaxWidth())
                            Spacer(modifier = Modifier.height(20.dp))
                        }
                    }
                    5 -> {
                        Column(modifier = Modifier.fillMaxSize()) {
                            Text("Selecciona Horario Disponible", fontWeight = FontWeight.Bold, fontSize = 20.sp, color = SannaPrimary)
                            Text("Fecha seleccionada: $fecha - $selectedMedicoNombre", fontSize = 13.sp, color = SannaSecondaryText)
                            Spacer(modifier = Modifier.height(16.dp))

                            val horariosList = listOf(
                                "08:00 AM", "08:30 AM", "09:00 AM", "09:30 AM",
                                "10:00 AM", "10:30 AM", "11:00 AM", "11:30 AM",
                                "12:00 PM", "03:00 PM", "03:30 PM", "04:00 PM"
                            )

                            LazyVerticalGrid(
                                columns = GridCells.Fixed(2),
                                horizontalArrangement = Arrangement.spacedBy(10.dp),
                                verticalArrangement = Arrangement.spacedBy(10.dp),
                                modifier = Modifier.weight(1f)
                            ) {
                                items(horariosList) { h ->
                                    val isSel = hora == h
                                    Card(
                                        shape = RoundedCornerShape(12.dp),
                                        colors = CardDefaults.cardColors(containerColor = if (isSel) SannaPrimary else SannaSurface),
                                        border = BorderStroke(1.dp, if (isSel) SannaPrimary else SannaBorder),
                                        modifier = Modifier.clickable {
                                            hora = h
                                            step = 6
                                        }
                                    ) {
                                        Box(modifier = Modifier.padding(14.dp), contentAlignment = Alignment.Center) {
                                            Text(
                                                text = h,
                                                fontWeight = FontWeight.Bold,
                                                fontSize = 14.sp,
                                                color = if (isSel) SannaOnPrimary else SannaPrimary
                                            )
                                        }
                                    }
                                }
                            }
                        }
                    }
                    6 -> {
                        Column(
                            modifier = Modifier
                                .fillMaxSize()
                                .verticalScroll(rememberScrollState())
                        ) {
                            Text("Modalidad y Cobertura de Seguro", fontWeight = FontWeight.Bold, fontSize = 20.sp, color = SannaPrimary)
                            Text("Paso 6 de 7 - Selección de beneficios", fontSize = 13.sp, color = SannaSecondaryText)
                            Spacer(modifier = Modifier.height(16.dp))

                            Text("1. Modalidad de Atención:", fontSize = 14.sp, fontWeight = FontWeight.Bold, color = SannaPrimary)
                            Spacer(modifier = Modifier.height(8.dp))

                            Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                                Card(
                                    shape = RoundedCornerShape(12.dp),
                                    colors = CardDefaults.cardColors(containerColor = if (modalidad == "Presencial en Sede") SannaSecondary else SannaSurface),
                                    border = BorderStroke(if (modalidad == "Presencial en Sede") 2.dp else 1.dp, SannaPrimary),
                                    modifier = Modifier
                                        .weight(1f)
                                        .clickable { modalidad = "Presencial en Sede" }
                                ) {
                                    Column(modifier = Modifier.padding(12.dp)) {
                                        Text("🏥 Presencial", fontWeight = FontWeight.Bold, fontSize = 14.sp, color = SannaPrimary)
                                        Text("En clínica SANNA", fontSize = 12.sp, color = SannaSecondaryText)
                                    }
                                }
                                Card(
                                    shape = RoundedCornerShape(12.dp),
                                    colors = CardDefaults.cardColors(containerColor = if (modalidad == "Teleconsulta SANNA") SannaSecondary else SannaSurface),
                                    border = BorderStroke(if (modalidad == "Teleconsulta SANNA") 2.dp else 1.dp, SannaPrimary),
                                    modifier = Modifier
                                        .weight(1f)
                                        .clickable { modalidad = "Teleconsulta SANNA" }
                                ) {
                                    Column(modifier = Modifier.padding(12.dp)) {
                                        Text("💻 Teleconsulta", fontWeight = FontWeight.Bold, fontSize = 14.sp, color = SannaPrimary)
                                        Text("En línea", fontSize = 12.sp, color = SannaSecondaryText)
                                    }
                                }
                            }

                            Spacer(modifier = Modifier.height(20.dp))
                            Text("2. Cobertura de Seguro Médico:", fontSize = 14.sp, fontWeight = FontWeight.Bold, color = SannaPrimary)
                            Spacer(modifier = Modifier.height(8.dp))

                            val isParticularSel = selectedAseguradoraId == null
                            Card(
                                shape = RoundedCornerShape(12.dp),
                                colors = CardDefaults.cardColors(containerColor = if (isParticularSel) SannaSecondary else SannaSurface),
                                border = BorderStroke(if (isParticularSel) 2.dp else 1.dp, if (isParticularSel) SannaPrimary else SannaBorder),
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .padding(vertical = 4.dp)
                                    .clickable {
                                        selectedAseguradoraId = null
                                        selectedAseguradoraNombre = "Particular / Sin Seguro"
                                    }
                            ) {
                                Column(modifier = Modifier.padding(14.dp)) {
                                    Text("Particular / Sin Seguro", fontWeight = FontWeight.Bold, fontSize = 14.sp, color = SannaPrimary)
                                    Text("Tarifa Base: S/ $tarifaBase", fontSize = 12.sp, color = SannaSecondaryText)
                                }
                            }

                            aseguradoras.forEach { aseg ->
                                val isSel = selectedAseguradoraId == aseg.id
                                Card(
                                    shape = RoundedCornerShape(12.dp),
                                    colors = CardDefaults.cardColors(containerColor = if (isSel) SannaSecondary else SannaSurface),
                                    border = BorderStroke(if (isSel) 2.dp else 1.dp, if (isSel) SannaPrimary else SannaBorder),
                                    modifier = Modifier
                                        .fillMaxWidth()
                                        .padding(vertical = 4.dp)
                                        .clickable {
                                            selectedAseguradoraId = aseg.id
                                            selectedAseguradoraNombre = aseg.nombre
                                        }
                                ) {
                                    Column(modifier = Modifier.padding(14.dp)) {
                                        Text(aseg.nombre, fontWeight = FontWeight.Bold, fontSize = 14.sp, color = SannaPrimary)
                                        Text("RUC: ${aseg.ruc} - Cobertura de Convenio Aplicada", fontSize = 12.sp, color = SannaSuccess)
                                    }
                                }
                            }

                            Spacer(modifier = Modifier.height(24.dp))
                            MinimalButton(
                                text = "Continuar a Pasarela de Pago",
                                onClick = { step = 7 },
                                modifier = Modifier.fillMaxWidth()
                            )
                            Spacer(modifier = Modifier.height(24.dp))
                        }
                    }
                    7 -> {
                        Column(
                            modifier = Modifier
                                .fillMaxSize()
                                .verticalScroll(rememberScrollState())
                        ) {
                            Text("Pasarela de Pago y Resumen", fontWeight = FontWeight.Bold, fontSize = 20.sp, color = SannaPrimary)
                            Text("Selecciona el medio de pago e ingresa tus datos", fontSize = 13.sp, color = SannaSecondaryText)
                            Spacer(modifier = Modifier.height(16.dp))

                            MinimalCard {
                                Column(modifier = Modifier.padding(16.dp)) {
                                    Row(
                                        modifier = Modifier.fillMaxWidth(),
                                        horizontalArrangement = Arrangement.SpaceBetween,
                                        verticalAlignment = Alignment.CenterVertically
                                    ) {
                                        Text("RESUMEN DE RESERVA", fontSize = 11.sp, fontWeight = FontWeight.Bold, color = SannaSecondaryText)
                                        Icon(imageVector = Icons.Default.Lock, contentDescription = "Pago Seguro", tint = SannaSecondaryText, modifier = Modifier.size(16.dp))
                                    }
                                    Spacer(modifier = Modifier.height(8.dp))
                                    Text("Sede: $selectedSedeNombre", fontWeight = FontWeight.Bold, fontSize = 14.sp, color = SannaPrimary)
                                    Text("Especialidad: $selectedEspNombre - $selectedMedicoNombre", fontSize = 13.sp, color = SannaPrimary)
                                    Text("Fecha y Hora: $fecha a las $hora", fontWeight = FontWeight.SemiBold, fontSize = 13.sp, color = SannaPrimary)
                                    Text("Modalidad: $modalidad", fontSize = 13.sp, color = SannaSecondaryText)
                                    Text("Seguro / Cobertura: $selectedAseguradoraNombre", fontSize = 13.sp, color = SannaSecondaryText)
                                    HorizontalDivider(modifier = Modifier.padding(vertical = 10.dp), color = SannaBorder)
                                    Row(
                                        modifier = Modifier.fillMaxWidth(),
                                        horizontalArrangement = Arrangement.SpaceBetween
                                    ) {
                                        Text("Monto Total a Pagar:", fontWeight = FontWeight.Bold, fontSize = 15.sp, color = SannaPrimary)
                                        Text("S/ ${String.format(Locale.US, "%.2f", montoFinalCalculado)}", fontWeight = FontWeight.Bold, fontSize = 18.sp, color = SannaPrimary)
                                    }
                                }
                            }

                            Spacer(modifier = Modifier.height(18.dp))
                            Text("Selecciona Método de Pago:", fontSize = 14.sp, fontWeight = FontWeight.Bold, color = SannaPrimary)
                            Spacer(modifier = Modifier.height(8.dp))

                            val metodos = listOf("Tarjeta de Crédito / Débito", "Yape / PLIN", "Pago Presencial en Caja")
                            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                                metodos.forEach { m ->
                                    val isSel = metodoPago == m
                                    Card(
                                        shape = RoundedCornerShape(10.dp),
                                        colors = CardDefaults.cardColors(containerColor = if (isSel) SannaSecondary else SannaSurface),
                                        border = BorderStroke(if (isSel) 2.dp else 1.dp, if (isSel) SannaPrimary else SannaBorder),
                                        modifier = Modifier
                                            .weight(1f)
                                            .clickable { metodoPago = m; pagoErrorMsg = null }
                                    ) {
                                        Box(modifier = Modifier.padding(vertical = 10.dp, horizontal = 6.dp), contentAlignment = Alignment.Center) {
                                            Text(
                                                text = when (m) {
                                                    "Tarjeta de Crédito / Débito" -> "💳 Tarjeta"
                                                    "Yape / PLIN" -> "📱 Yape/PLIN"
                                                    else -> "🏥 En Caja"
                                                },
                                                fontSize = 12.sp,
                                                fontWeight = FontWeight.Bold,
                                                color = SannaPrimary
                                            )
                                        }
                                    }
                                }
                            }

                            Spacer(modifier = Modifier.height(16.dp))

                            if (metodoPago == "Tarjeta de Crédito / Débito") {
                                MinimalTextField(
                                    value = numeroTarjeta,
                                    onValueChange = {
                                        if (it.length <= 16 && it.all { c -> c.isDigit() }) numeroTarjeta = it
                                    },
                                    label = "Número de Tarjeta (16 dígitos)"
                                )
                                Spacer(modifier = Modifier.height(10.dp))
                                MinimalTextField(
                                    value = nombreTitular,
                                    onValueChange = { nombreTitular = it },
                                    label = "Nombre del Titular de la Tarjeta"
                                )
                                Spacer(modifier = Modifier.height(10.dp))
                                Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                                    MinimalTextField(
                                        value = fechaExpira,
                                        onValueChange = { if (it.length <= 5) fechaExpira = it },
                                        label = "Vencimiento (MM/YY)",
                                        modifier = Modifier.weight(1f)
                                    )
                                    MinimalTextField(
                                        value = cvv,
                                        onValueChange = { if (it.length <= 4 && it.all { c -> c.isDigit() }) cvv = it },
                                        label = "CVV (3-4 dígitos)",
                                        modifier = Modifier.weight(1f)
                                    )
                                }
                            } else if (metodoPago == "Yape / PLIN") {
                                MinimalTextField(
                                    value = celularYape,
                                    onValueChange = { if (it.length <= 9 && it.all { c -> c.isDigit() }) celularYape = it },
                                    label = "Número Celular Yape/PLIN (9 dígitos)"
                                )
                                Spacer(modifier = Modifier.height(10.dp))
                                MinimalTextField(
                                    value = codigoYape,
                                    onValueChange = { if (it.length <= 6) codigoYape = it },
                                    label = "Código de Aprobación (6 dígitos)"
                                )
                            } else {
                                Surface(
                                    color = SannaSecondary,
                                    shape = RoundedCornerShape(12.dp),
                                    modifier = Modifier.fillMaxWidth()
                                ) {
                                    Text(
                                        text = "Podrás abonar el importe directamente en la recepción/caja de $selectedSedeNombre minutos antes de tu consulta.",
                                        fontSize = 13.sp,
                                        color = SannaSecondaryText,
                                        modifier = Modifier.padding(14.dp)
                                    )
                                }
                            }

                            Spacer(modifier = Modifier.height(12.dp))
                            MinimalTextField(
                                value = motivo,
                                onValueChange = { motivo = it },
                                label = "Motivo de la consulta (Opcional)"
                            )

                            if (pagoErrorMsg != null) {
                                Spacer(modifier = Modifier.height(10.dp))
                                Text(pagoErrorMsg!!, color = SannaError, fontSize = 13.sp)
                            }

                            Spacer(modifier = Modifier.height(20.dp))

                            if (isProcessingPayment) {
                                Column(
                                    modifier = Modifier.fillMaxWidth().padding(16.dp),
                                    horizontalAlignment = Alignment.CenterHorizontally
                                ) {
                                    CircularProgressIndicator(color = SannaPrimary)
                                    Spacer(modifier = Modifier.height(8.dp))
                                    Text("Procesando pago de forma segura con SANNA Pay...", fontSize = 13.sp, color = SannaSecondaryText)
                                }
                            } else {
                                MinimalButton(
                                    text = "💳 Pagar S/ ${String.format(Locale.US, "%.2f", montoFinalCalculado)} y Confirmar",
                                    onClick = {
                                        pagoErrorMsg = null
                                        if (metodoPago == "Tarjeta de Crédito / Débito") {
                                            if (numeroTarjeta.length < 16) {
                                                pagoErrorMsg = "Ingrese un número de tarjeta válido de 16 dígitos"
                                                return@MinimalButton
                                            }
                                            if (nombreTitular.isBlank()) {
                                                pagoErrorMsg = "Ingrese el nombre del titular"
                                                return@MinimalButton
                                            }
                                            if (fechaExpira.length < 4) {
                                                pagoErrorMsg = "Ingrese fecha de vencimiento (MM/YY)"
                                                return@MinimalButton
                                            }
                                            if (cvv.length < 3) {
                                                pagoErrorMsg = "Ingrese código CVV válido"
                                                return@MinimalButton
                                            }
                                        } else if (metodoPago == "Yape / PLIN") {
                                            if (celularYape.length < 9) {
                                                pagoErrorMsg = "Ingrese número celular válido de 9 dígitos"
                                                return@MinimalButton
                                            }
                                            if (codigoYape.isBlank()) {
                                                pagoErrorMsg = "Ingrese el código de aprobación Yape/PLIN"
                                                return@MinimalButton
                                            }
                                        }

                                        isProcessingPayment = true
                                        val generatedTxn = "TXN-${System.currentTimeMillis().toString().takeLast(8)}"
                                        val generatedBol = "B001-00${System.currentTimeMillis().toString().takeLast(6)}"
                                        numOperacionGenerated = generatedTxn
                                        numBoletaGenerated = generatedBol

                                        if (selectedMedicoId != null && selectedSedeId != null && selectedEspId != null) {
                                            viewModel.reservarCita(
                                                pacienteId = pacienteId,
                                                medicoId = selectedMedicoId!!,
                                                sedeId = selectedSedeId!!,
                                                especialidadId = selectedEspId!!,
                                                fecha = fecha,
                                                hora = hora,
                                                motivo = motivo.ifBlank { "Consulta médica especializada" },
                                                aseguradoraId = selectedAseguradoraId,
                                                metodoPago = metodoPago,
                                                numeroOperacion = generatedTxn
                                            )
                                        }
                                    },
                                    modifier = Modifier.fillMaxWidth()
                                )
                            }
                            Spacer(modifier = Modifier.height(28.dp))
                        }
                    }
                    8 -> {
                        Column(
                            modifier = Modifier
                                .fillMaxSize()
                                .verticalScroll(rememberScrollState()),
                            horizontalAlignment = Alignment.CenterHorizontally
                        ) {
                            val checkScale by animateFloatAsState(
                                targetValue = if (isPaymentSuccessAnimated) 1f else 0.2f,
                                animationSpec = spring(dampingRatio = Spring.DampingRatioMediumBouncy),
                                label = "CheckScale"
                            )

                            Spacer(modifier = Modifier.height(10.dp))
                            Icon(
                                imageVector = Icons.Default.CheckCircle,
                                contentDescription = "Pago Éxito",
                                tint = SannaSuccess,
                                modifier = Modifier.size(64.dp).scale(checkScale)
                            )
                            Spacer(modifier = Modifier.height(8.dp))
                            Text("¡Pago y Reserva Aprobados!", fontSize = 20.sp, fontWeight = FontWeight.Bold, color = SannaPrimary)
                            Text("Tu cita médica ha sido programada exitosamente", fontSize = 13.sp, color = SannaSecondaryText)
                            Spacer(modifier = Modifier.height(18.dp))

                            Card(
                                shape = RoundedCornerShape(16.dp),
                                colors = CardDefaults.cardColors(containerColor = SannaSurface),
                                border = BorderStroke(1.dp, SannaBorder),
                                modifier = Modifier.fillMaxWidth()
                            ) {
                                Column(modifier = Modifier.padding(20.dp)) {
                                    Row(
                                        modifier = Modifier.fillMaxWidth(),
                                        horizontalArrangement = Arrangement.SpaceBetween,
                                        verticalAlignment = Alignment.CenterVertically
                                    ) {
                                        Column {
                                            Text("SANNA", fontWeight = FontWeight.Bold, fontSize = 18.sp, color = SannaPrimary)
                                            Text("Clínicas y Centros Médicos", fontSize = 11.sp, color = SannaSecondaryText)
                                        }
                                        Icon(imageVector = Icons.Default.ReceiptLong, contentDescription = "Voucher", tint = SannaPrimary)
                                    }

                                    HorizontalDivider(modifier = Modifier.padding(vertical = 12.dp), color = SannaBorder)

                                    Text("BOLETA ELECTRÓNICA: $numBoletaGenerated", fontWeight = FontWeight.Bold, fontSize = 13.sp, color = SannaPrimary)
                                    Text("N° Operación Transacción: $numOperacionGenerated", fontSize = 12.sp, color = SannaSecondaryText)
                                    Spacer(modifier = Modifier.height(10.dp))

                                    Text("DATOS DE LA CITACION", fontSize = 11.sp, fontWeight = FontWeight.Bold, color = SannaSecondaryText)
                                    Spacer(modifier = Modifier.height(4.dp))
                                    Text("Sede: $selectedSedeNombre", fontWeight = FontWeight.Bold, fontSize = 14.sp, color = SannaPrimary)
                                    Text("Especialidad: $selectedEspNombre", fontSize = 13.sp, color = SannaPrimary)
                                    Text("Atendido por: $selectedMedicoNombre", fontSize = 13.sp, color = SannaPrimary)
                                    Text("Fecha de cita: $fecha a las $hora", fontWeight = FontWeight.Bold, fontSize = 13.sp, color = SannaPrimary)
                                    Text("Modalidad: $modalidad", fontSize = 13.sp, color = SannaSecondaryText)

                                    HorizontalDivider(modifier = Modifier.padding(vertical = 12.dp), color = SannaBorder)

                                    Text("DETALLE DE PAGO Y COBERTURA", fontSize = 11.sp, fontWeight = FontWeight.Bold, color = SannaSecondaryText)
                                    Spacer(modifier = Modifier.height(4.dp))
                                    Text("Seguro / Convenio: $selectedAseguradoraNombre", fontSize = 13.sp, color = SannaPrimary)
                                    Text("Medio de Pago: $metodoPago", fontSize = 13.sp, color = SannaPrimary)
                                    Spacer(modifier = Modifier.height(6.dp))

                                    Row(
                                        modifier = Modifier.fillMaxWidth(),
                                        horizontalArrangement = Arrangement.SpaceBetween
                                    ) {
                                        Text("TOTAL PAGADO:", fontWeight = FontWeight.Bold, fontSize = 15.sp, color = SannaPrimary)
                                        Text("S/ ${String.format(Locale.US, "%.2f", montoFinalCalculado)}", fontWeight = FontWeight.Bold, fontSize = 16.sp, color = SannaSuccess)
                                    }

                                    Spacer(modifier = Modifier.height(14.dp))
                                    Row(
                                        modifier = Modifier.fillMaxWidth(),
                                        horizontalArrangement = Arrangement.Center,
                                        verticalAlignment = Alignment.CenterVertically
                                    ) {
                                        Icon(imageVector = Icons.Default.QrCode, contentDescription = "QR Code", modifier = Modifier.size(36.dp), tint = SannaPrimary)
                                        Spacer(modifier = Modifier.width(8.dp))
                                        Text("Comprobante Digital Verificado por SANNA", fontSize = 11.sp, color = SannaSecondaryText)
                                    }
                                }
                            }

                            Spacer(modifier = Modifier.height(20.dp))

                            MinimalButton(
                                text = "🖨️ Ver / Imprimir Voucher PDF",
                                onClick = {
                                },
                                modifier = Modifier.fillMaxWidth(),
                                isPrimary = false
                            )

                            Spacer(modifier = Modifier.height(10.dp))

                            MinimalButton(
                                text = "Finalizar e ir a Mis Citas",
                                onClick = {
                                    viewModel.resetBookingResult()
                                    onBookingSuccess()
                                },
                                modifier = Modifier.fillMaxWidth()
                            )
                            Spacer(modifier = Modifier.height(28.dp))
                        }
                    }
                }
            }
        }
    }
